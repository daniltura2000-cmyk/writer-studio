/// Чи слово (у нижньому регістрі) є службовим в uk/ru/en.
pub fn is_stopword(word_lower: &str) -> bool {
    STOPWORDS_UK.contains(&word_lower)
        || STOPWORDS_RU.contains(&word_lower)
        || STOPWORDS_EN.contains(&word_lower)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn each_list_has_at_least_100_unique_words() {
        for (name, list) in [
            ("uk", STOPWORDS_UK),
            ("ru", STOPWORDS_RU),
            ("en", STOPWORDS_EN),
        ] {
            let uniq: HashSet<&str> = list.iter().copied().collect();
            assert!(
                list.len() >= 100,
                "список {name} містить лише {} слів",
                list.len()
            );
            assert!(
                uniq.len() >= 100,
                "список {name} має лише {} УНІКАЛЬНИХ слів",
                uniq.len()
            );
        }
    }

    #[test]
    fn known_defect_words_are_filtered() {
        for w in [
            "казалось", "почему", "когда", "может", "нельзя", "дальше", "потом", "каждый",
            "никто", "что-то", "все", "все-таки",
        ] {
            assert!(is_stopword(w), "ru стоп-слово «{w}» не відфільтроване");
        }
        for w in [
            "казалося", "чому", "коли", "мабуть", "далі", "потім", "кожен", "ніхто", "десь",
            "отже", "проте", "звісно",
        ] {
            assert!(is_stopword(w), "uk стоп-слово «{w}» не відфільтроване");
        }
        for w in ["seemed", "perhaps", "however", "therefore", "yesterday"] {
            assert!(is_stopword(w), "en стоп-слово «{w}» не відфільтроване");
        }
    }

    #[test]
    fn real_names_are_not_stopwords() {
        for w in ["кальдрін", "велес", "марія", "kaldryn", "aria"] {
            assert!(!is_stopword(w), "ім'я «{w}» помилково в стоп-листі");
        }
    }
}
